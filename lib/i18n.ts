export function translate(text: string, locale: Locale): string {
  if (!text) return text;
  if (locale === "zh-Hans") return text;

  const exact = DICTIONARIES[locale]?.[text];
  if (exact) return exact;

  const content =
    locale === "zh-Hant"
      ? (CONTENT_HANT[text] ??
        CONTENT_SUMMARY_HANT[text] ??
        CONTENT_PROS_HANT[text] ??
        CONTENT_CONS_HANT[text])
      : (CONTENT_EN[text] ??
        CONTENT_SUMMARY_EN[text] ??
        CONTENT_PROS_EN[text] ??
        CONTENT_CONS_EN[text]);
  if (content) return content;

  let output = text;
  for (const item of [...PHRASES, ...DESCRIPTIONS]) {
    const target = locale === "zh-Hant" ? item.hant : item.en;
    if (output.includes(item.zh)) output = output.split(item.zh).join(target);
  }
  return output;
}


